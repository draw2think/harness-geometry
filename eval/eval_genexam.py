def run_construct_anthropic(client, prob, prob_dir, slug) -> dict:
    """Two-phase agentic construction via Anthropic Messages API."""
    messages = [{"role": "user", "content": prob["prompt"]}]

    lazy     = _LazyGGB()
    tracker  = CanvasTracker()
    tok_i = tok_o = tok_think = tok_t = 0
    t0 = time.perf_counter(); t1 = None
    process_log: list[dict] = []
    phase = "construct"
    no_tool_streak = 0

    try:
        for turn in range(MAX_TURNS):
            print(f"  [LLM] turn {turn+1} (phase={phase}) — ", end="", flush=True)
            turn_entry = {"turn": turn + 1, "phase": phase, "tool_calls": []}

            include_render = (phase == "render")
            tools_def = build_anthropic_tools(include_render=include_render)

            kwargs = dict(
                model=MODEL,
                system=SYSTEM_PROMPT_CONSTRUCT,
                messages=messages,
                tools=tools_def,
                max_tokens=65536,
            )
            _tl = cfg.THINKING_LEVEL.lower() if cfg.THINKING_LEVEL else "high"
            if _tl != "off":
                eff = {"minimal": "low"}.get(_tl, _tl)
                if "4-5" in MODEL:
                    kwargs["thinking"] = {"type": "enabled", "budget_tokens": 10000}
                else:
                    kwargs["thinking"] = {"type": "adaptive"}
                if "sonnet-4-5" not in MODEL and \
                        eff in ("low", "medium", "high", "max"):
                    kwargs["output_config"] = {"effort": eff}

            if turn == 0 and _tl == "off":
                kwargs["tool_choice"] = {"type": "any"}
            else:
                kwargs["tool_choice"] = {"type": "auto"}

            with client.messages.stream(**kwargs) as stream:
                resp = stream.get_final_message()
            if t1 is None: t1 = time.perf_counter()

            if resp.usage:
                tok_i += getattr(resp.usage, "input_tokens", 0) or 0
                tok_o += getattr(resp.usage, "output_tokens", 0) or 0
                tok_t += tok_i + tok_o

            text = ""
            tool_uses = []
            for block in resp.content:
                btype = getattr(block, "type", "")
                if btype == "text":
                    text += block.text
                elif btype == "thinking":
                    tok_think += len(getattr(block, "thinking", "") or "") // 4
                elif btype == "tool_use":
                    tool_uses.append(block)

            if text:
                print(text[:120].strip(), flush=True)

            # Phase signal detection
            signal = _detect_phase_signal(text)
            if signal == "complete":
                print("  [SIGNAL] CONSTRUCTION_COMPLETE")
                process_log.append(turn_entry)
                break
            if signal == "geometry_done" and phase == "construct":
                print("  [SIGNAL] GEOMETRY_DONE -> switching to render phase")
                phase = "render"
                no_tool_streak = 0
                messages.append({"role": "assistant", "content": resp.content})
                messages.append({"role": "user", "content": RENDER_INJECTION})
                process_log.append(turn_entry)
                continue

            # Tool calls
            if not tool_uses:
                no_tool_streak += 1
                if no_tool_streak >= 2:
                    print(f"  [AUTO-STOP] {no_tool_streak} turns without tool calls")
                    process_log.append(turn_entry)
                    break
                process_log.append(turn_entry)
                # Must still append assistant content for Anthropic message format
                messages.append({"role": "assistant", "content": resp.content})
                continue
            else:
                no_tool_streak = 0

            tool_results = []
            for tu in tool_uses:
                fn_name = tu.name
                args = tu.input if isinstance(tu.input, dict) else {}
                ggb = lazy.get()
                result, log_entry = tracker.execute(ggb, fn_name, args)
                _print_tool_result(fn_name, log_entry)
                turn_entry["tool_calls"].append(log_entry)
                tool_results.append({
                    "type": "tool_result",
                    "tool_use_id": tu.id,
                    "content": json.dumps(result, ensure_ascii=False),
                })

            messages.append({"role": "assistant", "content": resp.content})
            messages.append({"role": "user", "content": tool_results})
            process_log.append(turn_entry)

    except TimeoutError as te:
        print(f"  [SKIP] {te}", flush=True)

    png_path = _finalize_genexam_ggb(lazy, prob_dir, slug, tracker=tracker)
    tend = time.perf_counter()
    return {
        "png_path": png_path,
        "tools_ok": tracker.ok_n, "tools_fail": tracker.fail_n,
        "tools_total": tracker.total_n,
        "process": {"total_turns": len(process_log), "turns": process_log},
        "metrics": {
            "input_tokens": tok_i, "output_tokens": tok_o,
            "thought_tokens": tok_think, "total_tokens": tok_t,
            "ggb_used": lazy.used,
            "t_total_sec": round(tend - t0, 3),
        },
    }


# ── Judge (GPT-5 vision) ─────────────────────────────────────────────────────

def _encode_image(image_path: str, target_size: int = 768) -> str:
    """Encode image to base64 with optional resize (matching official pipeline)."""
    from PIL import Image
    img = Image.open(image_path)
    if img.mode in ("RGBA", "P"):
        img = img.convert("RGB")
    if target_size and target_size > 0:
        w, h = img.size
        if max(w, h) > target_size:
            if w >= h:
                new_w, new_h = target_size, int(h * target_size / w)
            else:
                new_h, new_w = target_size, int(w * target_size / h)
            img = img.resize((new_w, new_h), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, format="JPEG")
    return base64.b64encode(buf.getvalue()).decode("utf-8")


def judge_single(gen_img: str, gt_img: str, prompt: str,
                 scoring_points: list[dict],
                 judge_model: str = None) -> dict:
    """Call GPT-5 judge to evaluate generated image vs ground truth.

    Returns parsed JSON with 'answers' and 'global_evaluation'.
    """
    from openai import OpenAI
    from symbolic.utils.env_loader import load_env_file
    load_env_file()

    judge_model = judge_model or JUDGE_MODEL

    # Judge uses proxy if USE_JUDGE_PROXY=1 or USE_PROXY=1
    _judge_proxy = (os.environ.get("USE_JUDGE_PROXY", "").strip() == "1"
                    or os.environ.get("USE_PROXY", "").strip() == "1")
    if _judge_proxy:
        judge_client = OpenAI(
            api_key=os.environ["PROXY_API_KEY"],
            base_url=os.environ.get("PROXY_BASE_URL", "") + "/v1",
        )
    else:
        judge_client = OpenAI()

    sp_questions = [sp["question"] for sp in scoring_points]
    text_prompt = JUDGE_PROMPT.format(
        prompt=prompt,
        scoring_points=sp_questions,
    )

    gen_b64 = _encode_image(gen_img)
    gt_b64 = _encode_image(gt_img)

    content = [
        {"type": "text", "text": text_prompt},
        {"type": "image_url", "image_url": {
            "url": f"data:image/jpeg;base64,{gen_b64}", "detail": "high"}},
        {"type": "image_url", "image_url": {
            "url": f"data:image/jpeg;base64,{gt_b64}", "detail": "high"}},
    ]

    for attempt in range(3):
        try:
            resp = judge_client.chat.completions.create(
                model=judge_model,
                messages=[{"role": "user", "content": content}],
                max_completion_tokens=16384,
                reasoning_effort="low",
                response_format={"type": "json_object"},
            )
            raw = resp.choices[0].message.content

            # Parse JSON (handle ```json ... ``` wrapping)
            text = raw.split("```json")[-1].split("```")[0]
            # Fix curly/smart quotes and dashes from GPT-5
            text = text.replace("\u2018", "'").replace("\u2019", "'")
            text = text.replace("\u201c", '"').replace("\u201d", '"')
            text = text.replace("\u2014", "--").replace("\u2013", "-")
            try:
                result = json.loads(text)
            except json.JSONDecodeError:
                # GPT-5 sometimes puts unescaped newlines/control chars
                # inside JSON string values. Sanitize them.
                import re
                cleaned = re.sub(r'[\x00-\x1f]', lambda m: {
                    '\n': '\\n', '\r': '\\r', '\t': '\\t'
                }.get(m.group(), ''), text)
                try:
                    result = json.loads(cleaned)
                except json.JSONDecodeError:
                    result = ast.literal_eval(cleaned)

            # Validate
            assert "global_evaluation" in result and "answers" in result
            assert len(result["answers"]) == len(scoring_points), \
                f"Expected {len(scoring_points)} answers, got {len(result['answers'])}"
            assert all(item["answer"] in [0, 1] for item in result["answers"])
            assert all(k in result["global_evaluation"]
                       for k in ("Clarity and Readability", "Logical Consistency", "Spelling"))
            return result

        except Exception as e:
            print(f"  [JUDGE] attempt {attempt+1} failed: {e}", flush=True)
            if attempt == 2:
                raise ValueError(f"Judge failed after 3 attempts: {e}")


# ── Score calculation (official GenExam formula) ──────────────────────────────

def cal_score_single(eval_result: dict) -> dict:
    """Compute strict and relaxed scores from judge output.

    eval_result must have 'answers', 'scoring_points', 'global_evaluation'.
    """
    assert round(sum(item["score"] for item in eval_result["scoring_points"]), 4) == 1, \
        f"Invalid sum of scoring point scores: {sum(item['score'] for item in eval_result['scoring_points'])}"

    scoring_point_scores = 0
    for idx, answer in enumerate(eval_result["answers"]):
        if answer["answer"] == 1:
            scoring_point_scores += eval_result["scoring_points"][idx]["score"]

    scores = {
        "semantic_correctness": round(scoring_point_scores, 4),
        "readability": eval_result["global_evaluation"]["Clarity and Readability"]["score"],
        "logical_consistency": eval_result["global_evaluation"]["Logical Consistency"]["score"],
        "spelling": eval_result["global_evaluation"]["Spelling"]["score"],
    }
    scores["scoring_point_all_correct"] = all(
        item["answer"] == 1 for item in eval_result["answers"])
    scores["strict_score"] = int(
        scores["scoring_point_all_correct"]
        and scores["spelling"] == 2
        and scores["readability"] == 2
        and scores["logical_consistency"] == 2)
    scores["relaxed_score"] = round(
        scores["semantic_correctness"] * 0.7
        + scores["spelling"] * 0.1 / 2
        + scores["readability"] * 0.1 / 2
        + scores["logical_consistency"] * 0.1 / 2, 3)

    return scores


# ── Problem runner ────────────────────────────────────────────────────────────

def run_problem(client, prob: dict, prob_dir: Path, slug: str,
                phase: str = "all") -> dict:
    """Run a single GenExam problem through construct → judge → score pipeline.

    phase: "all" | "generate" | "judge" | "score"
    """
    prob_dir.mkdir(parents=True, exist_ok=True)
    print(f"\n{'='*64}")
    print(f"  [genexam]  id={prob['id']}  difficulty={prob.get('difficulty', '?')}"
          f"  model={MODEL_ID}  phase={phase}")
    print(f"  {prob['prompt'][:120]}{'...' if len(prob['prompt'])>120 else ''}")
    print(f"  Scoring points: {len(prob['scoring_points'])}")
    print(f"{'='*64}")

    construct_result = None
    judge_result = None
    score_result = None
    png_path = None

    # ── Phase A+B: Construct ──
    if phase in ("all", "generate"):
        if SDK_TYPE == "google-genai":
            construct_result = run_construct_gemini(client, prob, prob_dir, slug)
        elif SDK_TYPE == "openai":
            construct_result = run_construct_openai(client, prob, prob_dir, slug)
        elif SDK_TYPE == "anthropic":
            construct_result = run_construct_anthropic(client, prob, prob_dir, slug)
        else:
            raise NotImplementedError(f"SDK '{SDK_TYPE}' not supported")

        png_path = construct_result.get("png_path")

        # Save construct log
        (prob_dir / f"{slug}_construct.json").write_text(
            json.dumps(construct_result, indent=2, ensure_ascii=False))

        m = construct_result["metrics"]
        in_tok = m.get('input_tokens', 0)
        out_tok = m.get('output_tokens', 0) + m.get('thought_tokens', 0)
        print(f"\n  Construct: tools={construct_result['tools_ok']}ok/"
              f"{construct_result['tools_fail']}fail  "
              f"in={in_tok}  out={out_tok}"
              f"({m.get('output_tokens',0)}+{m.get('thought_tokens',0)}think)  "
              f"time={m['t_total_sec']:.1f}s"
              f"  png={'YES' if png_path else 'NO'}")

    # ── Phase C: Judge ──
    if phase in ("all", "judge"):
        if png_path is None:
            # Look for existing PNG
            existing = prob_dir / f"{slug}_canvas.png"
            if existing.exists():
                png_path = str(existing)

        gt_img = prob.get("gt_image", "")
        if png_path and gt_img and Path(gt_img).exists():
            print(f"  [JUDGE] Evaluating with {JUDGE_MODEL}...")
            try:
                judge_result = judge_single(
                    gen_img=png_path,
                    gt_img=gt_img,
                    prompt=prob["prompt"],
                    scoring_points=prob["scoring_points"],
                )
                (prob_dir / f"{slug}_judge.json").write_text(
                    json.dumps(judge_result, indent=2, ensure_ascii=False))
                print(f"  [JUDGE] Done: {sum(a['answer'] for a in judge_result['answers'])}"
                      f"/{len(judge_result['answers'])} scoring points passed")
            except Exception as e:
                print(f"  [JUDGE] Failed: {e}")
        elif not png_path:
            print("  [JUDGE] Skipped: no generated PNG")
        elif not gt_img or not Path(gt_img).exists():
            print(f"  [JUDGE] Skipped: ground truth image not found ({gt_img})")

    # ── Phase D: Score ──
    if phase in ("all", "score", "judge"):
        if judge_result is None:
            # Try loading existing judge result
            judge_path = prob_dir / f"{slug}_judge.json"
            if judge_path.exists():
                judge_result = json.loads(judge_path.read_text())

        if judge_result:
            # Merge scoring_points into judge_result for cal_score_single
            judge_with_sp = {**judge_result, "scoring_points": prob["scoring_points"]}
            score_result = cal_score_single(judge_with_sp)

            # Save result
            result_data = {
                "id": prob["id"],
                "prompt": prob["prompt"],
                "taxonomy": prob.get("taxonomy", ""),
                "difficulty": prob.get("difficulty", ""),
                "model": MODEL_ID,
                "png_path": png_path,
                "gt_image": prob.get("gt_image", ""),
                **score_result,
            }
            if construct_result:
                result_data["construct_metrics"] = construct_result["metrics"]
            (prob_dir / f"{slug}_result.json").write_text(
                json.dumps(result_data, indent=2, ensure_ascii=False))

            print(f"\n  Score: strict={score_result['strict_score']}"
                  f"  relaxed={score_result['relaxed_score']:.3f}"
                  f"  semantic={score_result['semantic_correctness']:.3f}"
                  f"  spell={score_result['spelling']}"
                  f"  read={score_result['readability']}"
                  f"  logic={score_result['logical_consistency']}")
        else:
            print("  [SCORE] Skipped: no judge result available")

    return {
        "construct": construct_result,
        "judge": judge_result,
        "score": score_result,
        "png_path": png_path,
    }


