# ── Thread-safe TeeLog ────────────────────────────────────────────────────────

_thread_local = threading.local()
_real_stdout  = sys.stdout


class _ThreadDispatchStdout:
    def __init__(self, orig):
        self._orig = orig
        self._lock = threading.Lock()

    def write(self, data):
        tee = getattr(_thread_local, "tee", None)
        with self._lock:
            if tee:
                tee.write_both(data)
            else:
                self._orig.write(data)

    def flush(self):
        tee = getattr(_thread_local, "tee", None)
        with self._lock:
            if tee:
                tee.flush_both()
            else:
                self._orig.flush()

    def __getattr__(self, name):
        return getattr(self._orig, name)


sys.stdout = _ThreadDispatchStdout(_real_stdout)


class TeeLog:
    def __init__(self, path, mode="w"):
        self._path = Path(path)
        self._mode = mode          # "w" = overwrite, "a" = append
        self._file = None

    def __enter__(self):
        self._file = self._path.open(self._mode, encoding="utf-8")
        _thread_local.tee = self
        return self

    def write_both(self, data):
        _real_stdout.write(data)
        self._file.write(data)

    def flush_both(self):
        _real_stdout.flush()
        self._file.flush()

    def __exit__(self, *_):
        _thread_local.tee = None
        self._file.close()
        _real_stdout.write(f"  [LOG] {self._path}\n")


