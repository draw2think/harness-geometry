def run_construct_gemini(client, prob, prob_dir, slug) -> dict:
    """Two-phase agentic construction via Gemini API."""
    from google.genai import types

    is_3d = _is_solid(prob)

    def _gemini_config(turn: int, include_render: bool):
        fc_mode = types.FunctionCallingConfig(mode="ANY") if turn == 0 \
            else types.FunctionCallingConfig(mode="AUTO")
        thinking = None
        if cfg.THINKING_LEVEL:
            gem_level = "NONE" if cfg.THINKING_LEVEL.lower() == "off" \
                else cfg.THINKING_LEVEL.upper()
            thinking = types.ThinkingConfig(thinking_level=gem_level)
        # Merge 2D + 3D tools for solid problems
        tools_2d = build_gemini_tools(include_render=include_render)
        if is_3d:
            tools_3d = build_gemini_solid_tools(include_render=include_render)
            # Merge FunctionDeclarations from both tool lists
            all_decls = (tools_2d[0].function_declarations
                         + tools_3d[0].function_declarations)
            merged = [types.Tool(function_declarations=all_decls)]
        else:
            merged = tools_2d
        return types.GenerateContentConfig(
            tools=merged,
            tool_config=types.ToolConfig(function_calling_config=fc_mode),
            system_instruction=SYSTEM_PROMPT_CONSTRUCT,
            temperature=cfg.TEMPERATURE,
            thinking_config=thinking,
        )

    contents = [types.Content(role="user", parts=[
        types.Part(text=prob["prompt"]),
    ])]

    lazy     = _LazyGGB(enable_3d=is_3d)
    tracker  = CanvasTracker()
    tok_i = tok_o = tok_think = tok_t = 0
    t0 = time.perf_counter(); t1 = None
    process_log: list[dict] = []
    phase = "construct"
    no_tool_streak = 0

    try:
        for turn in range(MAX_TURNS):
            print(f"  [LLM] turn {turn+1} (phase={phase}) — ", end="", flush=True)
            turn_entry = {"turn": turn + 1, "phase": phase, "tool_calls": []}

            include_render = (phase == "render")
            _ttft_limit = cfg.TTFT_TIMEOUT
            if _ttft_limit:
                _pool = ThreadPoolExecutor(max_workers=1)
                _fut = _pool.submit(client.models.generate_content,
                                    model=MODEL, contents=contents,
                                    config=_gemini_config(turn, include_render))
                try:
                    resp = _fut.result(timeout=_ttft_limit)
                except FuturesTimeout:
                    _pool.shutdown(wait=False, cancel_futures=True)
                    print(f"\n  [TIMEOUT] turn {turn+1} exceeded {_ttft_limit}s")
                    raise TimeoutError(f"TTFT>{_ttft_limit}s")
                finally:
                    _pool.shutdown(wait=False)
            else:
                resp = client.models.generate_content(
                    model=MODEL, contents=contents,
                    config=_gemini_config(turn, include_render))
            if t1 is None: t1 = time.perf_counter()

            parts = (resp.candidates[0].content.parts or []) if resp.candidates else []
            for p in parts:
                if getattr(p, "text", None) and not getattr(p, "thought", False):
                    print(p.text[:120].strip(), end="", flush=True)
            print(flush=True)

            if u := getattr(resp, "usage_metadata", None):
                tok_i     += int(getattr(u, "prompt_token_count", None) or 0)
                tok_o     += int(getattr(u, "candidates_token_count", None) or 0)
                tok_think += int(getattr(u, "thoughts_token_count", None) or 0)
                tok_t     += int(getattr(u, "total_token_count", None) or 0)

            history_parts = [p for p in parts
                             if not getattr(p, "thought", False)
                             or getattr(p, "function_call", None)]
            contents.append(types.Content(role="model", parts=history_parts or parts))

            text = " ".join(p.text for p in parts if getattr(p, "text", None)
                            and not getattr(p, "thought", False))

            # Phase signal detection
            signal = _detect_phase_signal(text)
            if signal == "complete":
                print("  [SIGNAL] CONSTRUCTION_COMPLETE")
                process_log.append(turn_entry)
                break
            if signal == "geometry_done" and phase == "construct":
                print("  [SIGNAL] GEOMETRY_DONE -> switching to render phase")
                phase = "render"
                no_tool_streak = 0
                render_text = RENDER_INJECTION
                # 3D: append scene bounding box so LLM can set appropriate zoom
                if is_3d:
                    try:
                        _ggb = lazy.get()
                        _st = _ggb.get_construction_state()
                        _pts_3d = []
                        for info in _st["objects"].values():
                            if info.get("type") == "point" and "x" in info and "y" in info:
                                z = _ggb.get_coords_3d(info["name"])
                                zv = z[2] if z else 0
                                _pts_3d.append((info["x"], info["y"], zv))
                        if _pts_3d:
                            _xs = [p[0] for p in _pts_3d]
                            _ys = [p[1] for p in _pts_3d]
                            _zs = [p[2] for p in _pts_3d]
                            _span = max(max(_xs)-min(_xs),
                                        max(_ys)-min(_ys),
                                        max(_zs)-min(_zs), 1)
                            render_text += (
                                f"\n\nScene bounding box: "
                                f"x=[{min(_xs):.1f}, {max(_xs):.1f}], "
                                f"y=[{min(_ys):.1f}, {max(_ys):.1f}], "
                                f"z=[{min(_zs):.1f}, {max(_zs):.1f}], "
                                f"max span={_span:.1f}. "
                                f"Ensure all objects fit in frame — "
                                f"use a lower scale for large scenes.")
                    except Exception:
                        pass
                contents.append(types.Content(role="user", parts=[
                    types.Part(text=render_text)]))
                process_log.append(turn_entry)
                continue

            # Tool calls
            fcs = [p.function_call for p in parts
                   if getattr(p, "function_call", None)]
            if not fcs:
                no_tool_streak += 1
                if no_tool_streak >= 2:
                    print(f"  [AUTO-STOP] {no_tool_streak} turns without tool calls")
                    process_log.append(turn_entry)
                    break
                process_log.append(turn_entry)
                continue
            else:
                no_tool_streak = 0

            tool_parts = []
            for fc in fcs:
                args = dict(fc.args)
                ggb = lazy.get()
                if is_3d:
                    result, log_entry = exec_with_solid_routing(
                        tracker, ggb, fc.name, args)
                else:
                    result, log_entry = tracker.execute(ggb, fc.name, args)
                _print_tool_result(fc.name, log_entry)
                turn_entry["tool_calls"].append(log_entry)
                tool_parts.append(types.Part(function_response=types.FunctionResponse(
                    name=fc.name, response=result)))
            contents.append(types.Content(role="user", parts=tool_parts))
            process_log.append(turn_entry)

    except TimeoutError as te:
        print(f"  [SKIP] {te}", flush=True)

    png_path = _finalize_genexam_ggb(lazy, prob_dir, slug, tracker=tracker)
    tend = time.perf_counter()
    return {
        "png_path": png_path,
        "tools_ok": tracker.ok_n, "tools_fail": tracker.fail_n,
        "tools_total": tracker.total_n,
        "process": {"total_turns": len(process_log), "turns": process_log},
        "metrics": {
            "input_tokens": tok_i, "output_tokens": tok_o,
            "thought_tokens": tok_think, "total_tokens": tok_t,
            "ggb_used": lazy.used,
            "t_total_sec": round(tend - t0, 3),
        },
    }


