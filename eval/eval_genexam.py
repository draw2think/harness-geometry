# ── Lazy GeoGebra ─────────────────────────────────────────────────────────────

class _LazyGGB:
    def __init__(self, enable_3d: bool = False):
        self._ctx = self._ggb = None
        self._was_used = False
        self._enable_3d = enable_3d

    def get(self):
        if self._ggb is None:
            tag = "3D" if self._enable_3d else "2D"
            print(f"  [GGB] Starting Selenium ({tag})...", flush=True)
            self._ctx = GeoGebraAPI(mode="selenium", headless=True,
                                    enable_3d=self._enable_3d)
            self._ggb = self._ctx.__enter__()
            self._ggb.reset()
            self._was_used = True
        return self._ggb

    def close(self):
        if self._ctx is not None:
            self._ctx.__exit__(None, None, None)
            self._ctx = self._ggb = None

    @property
    def used(self): return self._was_used


# ── Tool result printing ─────────────────────────────────────────────────────

def _print_tool_result(fn_name: str, log_entry: dict):
    cmd = log_entry["cmd"]
    ok  = log_entry["ok"]
    tag = "OK  " if ok else "FAIL"
    # Classify by behaviour: query / display / construction
    _DISPLAY_TOOLS = {"set_label_visible", "set_object_visible", "rename_object"}
    is_display = fn_name.startswith("render_") or fn_name in _DISPLAY_TOOLS

    if fn_name.startswith("query_"):
        val = log_entry.get("value")
        suffix = f"  -> {log_entry['error']}" if not ok else ""
        print(f"    [{tag}] {cmd}  value={val}{suffix}", flush=True)
        if ok:
            print(f"           canvas: {json.dumps(log_entry['canvas'])}")
    elif is_display:
        suffix = f"  -> {log_entry['error']}" if not ok else ""
        print(f"    [{tag}] {cmd}{suffix}", flush=True)
        if ok:
            print(f"           applied: {log_entry.get('applied', '')}")
            print(f"           display: {json.dumps(log_entry.get('display', {}))}")
    else:
        suffix = f"  -> {log_entry['error']}" if not ok else ""
        print(f"    [{tag}] {cmd}{suffix}", flush=True)
        if ok:
            removed = log_entry.get("removed_objects", [])
            if removed:
                print(f"           removed: {removed}")
            print(f"           new: {json.dumps(log_entry.get('new_objects', []))}")
            print(f"           canvas: {json.dumps(log_entry.get('canvas', []))}")


# ── Phase signal detection ────────────────────────────────────────────────────

def _detect_phase_signal(text: str) -> str | None:
    """Detect phase transition signals in LLM output."""
    if not text:
        return None
    upper = text.upper()
    if "CONSTRUCTION_COMPLETE" in upper:
        return "complete"
    if "GEOMETRY_DONE" in upper:
        return "geometry_done"
    return None


# ── Canvas export (GenExam: no auto-label changes, LLM controls styling) ────

def _equalize_aspect_ratio(ggb, llm_viewport=None):
    """Equalize viewport aspect ratio to 1:1 before square PNG export.

    Computes point-based bounding box, unions with the LLM's explicit viewport
    (if any), then equalizes axes to 1:1.
    """
    try:
        state = ggb.get_construction_state()
        pts = [(info["x"], info["y"])
               for name, info in state["objects"].items()
               if info.get("type") == "point" and "x" in info and "y" in info
               and ggb.get_visible(name)]
        pad = 1.4
        if pts:
            xs, ys = [p[0] for p in pts], [p[1] for p in pts]
            xmin, xmax = min(xs) - pad, max(xs) + pad
            ymin, ymax = min(ys) - pad, max(ys) + pad
        else:
            xmin, xmax, ymin, ymax = -8, 8, -8, 8

        # Union with LLM's explicit viewport
        if llm_viewport:
            lx0, lx1, ly0, ly1 = llm_viewport
            xmin, xmax = min(xmin, lx0), max(xmax, lx1)
            ymin, ymax = min(ymin, ly0), max(ymax, ly1)

        # Equalize to 1:1 aspect ratio
        xspan, yspan = xmax - xmin, ymax - ymin
        if xspan < yspan:
            extra = (yspan - xspan) / 2.0
            xmin -= extra; xmax += extra
        elif xspan > yspan:
            extra = (xspan - yspan) / 2.0
            ymin -= extra; ymax += extra

        ggb.set_coord_system(xmin, xmax, ymin, ymax)
        tag = "merged (points ∪ LLM)" if llm_viewport else "fit_view"
        print(f"  [GGB] Viewport {tag}: [{xmin:.1f},{xmax:.1f}]×[{ymin:.1f},{ymax:.1f}]",
              flush=True)
    except Exception as e:
        print(f"  [GGB] Aspect ratio fix failed: {e}", flush=True)


def _finalize_genexam_ggb(lazy, prob_dir, slug, tracker=None) -> str | None:
    """Export canvas PNG. Returns path or None."""
    png_path = None
    if lazy.used and prob_dir is not None:
        try:
            png_path = prob_dir / f"{slug}_canvas.png"
            ggb = lazy._ggb
            # Check if there are renderable objects
            names = ggb.get_all_object_names()
            geo_types = {"point", "segment", "angle", "line", "ray", "vector",
                         "triangle", "quadrilateral", "polygon",
                         "circle", "conic", "arc", "function",
                         "inequality", "implicit", "curve",
                         "sphere", "cylinder", "cone", "prism", "pyramid",
                         "tetrahedron", "cube", "plane", "surface"}
            has_geo = any((ggb.get_object_type(n) or "").lower() in geo_types
                         for n in names)
            if has_geo:
                is_3d = lazy._enable_3d
                if is_3d:
                    # 3D: set_coord_system is 2D-only, use XML scale instead.
                    # Auto-fit: compute scale from point bounding box so all
                    # objects fit in the 800px viewport.
                    import re as _re, base64 as _b64
                    state = ggb.get_construction_state()
                    pts = [(info.get("x", 0), info.get("y", 0))
                           for info in state["objects"].values()
                           if info.get("type") == "point"
                           and "x" in info and "y" in info]
                    if pts:
                        xs = [p[0] for p in pts]
                        ys = [p[1] for p in pts]
                        # Include z span — in 3D perspective, z maps
                        # roughly vertically and often dominates height.
                        try:
                            _zs = []
                            for info in state["objects"].values():
                                if info.get("type") == "point" and "name" in info:
                                    c3 = ggb.get_coords_3d(info["name"])
                                    if c3:
                                        _zs.append(c3[2])
                            z_span = (max(_zs) - min(_zs)) if _zs else 0
                        except Exception:
                            z_span = 0
                        span = max(max(xs)-min(xs), max(ys)-min(ys), z_span, 1)
                        # Conservative: 50% fill to ensure nothing clipped
                        target_scale = int(800 * 0.5 / span)
                        target_scale = max(20, min(target_scale, 120))
                    else:
                        target_scale = 60
                    xml = ggb._execute_js("return ggbApplet.getXML()")
                    m = _re.search(r'scale="(\d+)"', xml)
                    cur_scale = int(m.group(1)) if m else 50
                    # Auto-fit: apply if LLM didn't adjust (default 50),
                    # or if target is smaller than current (scene too large)
                    need_xml_update = False
                    if cur_scale == 50 or target_scale < cur_scale:
                        xml = _re.sub(r'scale="\d+"',
                                      f'scale="{target_scale}"', xml)
                        need_xml_update = True
                        print(f"  [GGB] 3D auto-fit: scale {cur_scale} -> "
                              f"{target_scale} (span={span:.1f})",
                              flush=True)
                    # Always hide axes + plate for clean 3D output
                    xml = _re.sub(r'(<axis id="\d" show=")true',
                                  r'\1false', xml)
                    xml = _re.sub(r'<plate show="true"/>',
                                  '<plate show="false"/>', xml)
                    need_xml_update = True
                    if need_xml_update:
                        encoded = _b64.b64encode(xml.encode()).decode()
                        ggb._execute_js(f'ggbApplet.setXML(atob("{encoded}"))')
                else:
                    llm_vp = tracker._llm_viewport if tracker else None
                    _equalize_aspect_ratio(ggb, llm_viewport=llm_vp)
                ggb.export_png(png_path)
                print(f"  [GGB] Canvas saved -> {png_path}", flush=True)
            else:
                print("  [GGB] No geometric objects -- canvas skipped", flush=True)
                png_path = None
        except Exception as exc:
            print(f"  [GGB] Screenshot failed: {exc}", flush=True)
            png_path = None
    lazy.close()
    return str(png_path) if png_path else None


